-- Real PostgreSQL 16 test fixture (for validating abstraction neutrality after MySQL)

CREATE USER sqlm_ro WITH PASSWORD 'sqlm_ro_pw';
CREATE USER sqlm_rw WITH PASSWORD 'sqlm_rw_pw';

CREATE DATABASE sqlm_alt OWNER sqlm_rw;

\connect sqlm_demo

CREATE SCHEMA IF NOT EXISTS analytics AUTHORIZATION sqlm_rw;

CREATE TABLE public.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snowflake_id BIGINT NOT NULL,
    balance NUMERIC(38, 10) NOT NULL,
    note TEXT NULL,
    meta JSONB NULL,
    raw_bytes BYTEA NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

