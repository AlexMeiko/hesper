    (100, 99.5000000000, '正常中文备注', NULL, NULL);

CREATE TABLE analytics.metrics (
    id BIGSERIAL PRIMARY KEY,
    metric_name TEXT NOT NULL,
    val NUMERIC(20, 4) NOT NULL
);

INSERT INTO analytics.metrics (metric_name, val)
SELECT 'metric_' || g, (g * 1.25)::NUMERIC(20,4) FROM generate_series(1, 150) AS g;

CREATE SEQUENCE public.order_seq START 1000;
CREATE VIEW public.v_accounts AS SELECT id, snowflake_id, balance FROM public.accounts;

-- Writable probe table for Execute-Once INSERT ... RETURNING * and commit-unknown tests
CREATE TABLE public.write_probe (
    id BIGSERIAL PRIMARY KEY,
    tag TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

GRANT CONNECT ON DATABASE sqlm_demo TO sqlm_ro, sqlm_rw;
